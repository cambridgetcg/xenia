test('the record for step 6 holds no local path, names the gate, the sha256 of each file the step changed, and what it does not establish',t=>{
  const name='.hermes/verification/guest-side-step6.json';
  const text=read(name);
  assert.doesNotMatch(text,LOCAL,name);
  const record=JSON.parse(text);
  assert.match(record.observed_at,/^2026-\d\d-\d\d$/);
  assert.equal(record.base_revision,map.revisions['0f73c10']);
  assert.deepEqual(record.commits.map(item=>item.task),['atlas-data','atlas-wired','atlas-page-and-record']);
  for(const item of record.commits.slice(0,2))assert.match(item.commit,/^[0-9a-f]{40}$/);
  assert.equal(record.gate.default_run.command,'npm test');assert.equal(record.gate.default_run.exit_code,0);
  assert.equal(record.gate.with_real_starter.env_var,'XENIA_STARTER_TEST_PACKAGE');
  assert.doesNotMatch(record.gate.with_real_starter.command,/=\//,'the package path is not written down');
  for(const run of [record.gate.default_run,record.gate.with_real_starter]){
    assert.equal(run.groups.length,3);
    for(const group of run.groups){assert.equal(group.fail,0);assert.equal(group.tests,group.pass+group.skipped);}
  }
  assert.deepEqual(record.gate.generated_checks.map(item=>item.command),['node tools/render-motifs.mjs --check','node tools/render-covenant.mjs --check','node tools/render-adoption-schema.mjs --check']);
  for(const item of record.gate.generated_checks)assert.equal(item.exit_code,0,item.command);
  // The files the step changed, each by a relative path, with the sha256 of its bytes. Where git has the commit that
  // last wrote this record, they are the files changed between the base and that commit, as they are in it; before
  // that commit, the files changed between the base and the working tree, as they are on disk.
  for(const [file,digest] of Object.entries(record.sha256)){assert.equal(path.isAbsolute(file),false,file);assert.match(digest,/^[0-9a-f]{64}$/,file);}
  assert.equal(Object.hasOwn(record.sha256,name),false,'the record is not in its own map');
  for(const expected of ['agent-first/0.1/motifs.json','agent-first/0.1/motif-map.mjs',PAGE,TOOL,'tests/agent-first-motif-page.test.mjs'])assert.ok(Object.hasOwn(record.sha256,expected),expected);
  if(hasCommit(record.base_revision)){
    const carrier=git(['log','-1','--format=%H','--',name]).stdout.trim();
    const changed=carrier?git(['diff','--name-only',record.base_revision,carrier]).stdout:git(['diff','--name-only',record.base_revision]).stdout+git(['ls-files','--others','--exclude-standard']).stdout;
    const names=[...new Set(changed.split('\n').filter(Boolean))].filter(file=>file!==name).sort();
    assert.deepEqual(Object.keys(record.sha256).sort(),names);
    const bytesOf=file=>carrier?spawnSync('git',['-C',root,'show',`${carrier}:${file}`]).stdout:fs.readFileSync(path.join(root,file));
    for(const file of names)assert.equal(createHash('sha256').update(bytesOf(file)).digest('hex'),record.sha256[file],file);
  }else t.diagnostic('git does not have the base revision; the file list is not compared');
  assert.ok(record.sizes.motifs_index_bytes<=8192);
  assert.deepEqual(Object.keys(record.sizes.motifs_entry_bytes),ids);
  for(const bytes of Object.values(record.sizes.motifs_entry_bytes))assert.ok(bytes<=8192);
  assert.ok(Array.isArray(record.not_established)&&record.not_established.length>=6);
  for(const about of [/duty/,/conformance/,/mapping/,/caller/,/running service/,/real bundle|backend/])assert.ok(record.not_established.some(line=>about.test(line)),String(about));
  assert.ok(Array.isArray(record.walk.guessed)&&record.walk.guessed.length>=1,'the walk says where it had to guess');
});
