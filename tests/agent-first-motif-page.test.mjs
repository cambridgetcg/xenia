test('no document uses a retired name, except the page that says where each went',t=>{
  // The retired names: the kit plan's names and the kit map's ids that are not ids now, from the reconciliation, and
  // the kit map's titles of those ids where git has the revision, unless an entry still has that title (release kept
  // exit's). The other atlas's ids are all ids now.
  const rows=map.reconciliation.name_rows.filter(row=>['kit-map','kit-plan'].includes(row.vocabulary)&&!ids.includes(row.name)&&!ids.includes(row.name.toLowerCase()));
  const retired=rows.map(row=>row.name).filter(name=>!['change','exit'].includes(name));
  const full=map.revisions['0f73c10'];
  if(hasCommit(full)){
    const old=JSON.parse(git(['show',`${full}:agent-first/0.1/motifs.json`]).stdout);
    const titles=new Set(map.motifs.map(entry=>entry.title));
    const oldTitles=old.motifs.filter(motif=>!ids.includes(motif.id)).map(motif=>motif.name);
    assert.ok(oldTitles.includes('Change that stays attributable')&&titles.has('An exit that takes nothing with it'));
    retired.push(...oldTitles.filter(title=>!titles.has(title)));
  }else t.diagnostic('git does not have 0f73c10; the old titles are not read');
  // Words of the drawing the README had, and the old title of `change` as the Telescope guide wrote it.
  retired.push('Bounded work','legible choices','attributable change','Change stays attributable');
  assert.ok(retired.length>=10,`${retired.length} names`);
  const documents=git(['ls-files','--cached','--others','--exclude-standard','*.md','agent-first/**/*.mjs','agent-first/**/*.json']).stdout.split('\n').filter(Boolean)
    .filter(file=>!file.startsWith('.hermes/')&&!file.startsWith('node_modules/')&&exists(file));
  assert.ok(documents.length>=40,`${documents.length} files`);
  const allowed=new Set([PAGE,'agent-first/0.1/motifs.json']);
  const found=[];
  for(const file of documents){
    if(allowed.has(file))continue;
    const text=read(file).toLowerCase();
    for(const name of retired)if(text.includes(name.toLowerCase()))found.push(`${file}: ${name}`);
  }
  assert.deepEqual(found,[]);
  // The kit map's ids `change` and `exit` are ordinary words; they are looked for only as motif names in the README.
  assert.doesNotMatch(section(read('agent-first/0.1/README.md'),'## The motifs'),/\*\*(Change|Exit|Bounded work)\*\*/);
});

